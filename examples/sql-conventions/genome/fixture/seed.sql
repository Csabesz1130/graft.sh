  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,           -- audio, outdoor, kitchen, office
  price_cents INTEGER NOT NULL,
  weight_grams INTEGER,
  deleted_at TEXT
